#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate BempDiff release record / GitHub release notes from git log.

Usage: python gen-release-notes.py <version> <output_md>

The generated Markdown is written next to the installer (release/), matching
MTask's one-click publish layout. Pure stdlib, no third-party deps.
"""
import os
import subprocess
import sys


def _find_repo_root():
    """Walk up from this script to the nearest directory containing .git."""
    d = os.path.dirname(os.path.abspath(__file__))
    for _ in range(10):
        if os.path.isdir(os.path.join(d, ".git")):
            return d
        parent = os.path.dirname(d)
        if parent == d:
            break
        d = parent
    return os.getcwd()


ROOT = _find_repo_root()


def sh(cmd):
    try:
        out = subprocess.run(
            cmd, shell=True, capture_output=True, text=True, timeout=60,
            cwd=ROOT, encoding="utf-8", errors="replace",
        )
        return (out.stdout or "").strip()
    except Exception:
        return ""


def main():
    if len(sys.argv) < 3:
        sys.exit("usage: gen-release-notes.py <version> <output_md>")
    version = sys.argv[1]
    out_path = sys.argv[2]

    repo = sh("git remote get-url origin") or "(unknown)"
    branch = sh("git rev-parse --abbrev-ref HEAD") or "master"
    since = sh("git describe --tags --abbrev=0")

    if since:
        log = sh('git log ' + since + '..HEAD --no-merges --pretty=format:"- %s"')
        baseline = "since " + since
    else:
        log = sh('git log -20 --no-merges --pretty=format:"- %s"')
        baseline = "last 20 commits (no tag)"

    commits = [line for line in log.splitlines() if line.strip()]
    if not commits:
        commits = ["- (no new commits since " + (since or "the last release") + ")"]
    count = len(commits)

    asset = os.path.join(os.path.dirname(os.path.abspath(out_path)),
                         "BempDiff-" + version + "-setup.exe")
    if os.path.isfile(asset):
        size = os.path.getsize(asset)
        installer_line = (
            "- `BempDiff-" + version + "-setup.exe` — Windows x64 NSIS 安装包"
            "（" + format(size, ",") + " 字节）\n"
        )
    else:
        installer_line = (
            "- `BempDiff-" + version + "-setup.exe` — Windows x64 NSIS 安装包\n"
        )

    notes = (
        "# BempDiff " + version + "\n\n"
        "Auto-generated by 一键发布.bat\n\n"
        "- Branch: " + branch + "\n"
        "- Repo: " + repo + "\n"
        "- Baseline: " + baseline + "（" + str(count) + " commits）\n\n"
        "## 发布产物\n\n"
        + installer_line +
        "- `BempDiff-" + version + "-setup.exe.blockmap` — 增量更新索引，与安装包同目录\n\n"
        "## 安装指引\n\n"
        "- 双击安装包，按向导完成安装。\n"
        "- 首次启动后到「配置中心」填入 API Key。\n\n"
        "## 已知限制\n\n"
        "- 当前仅提供 Windows x64 安装包；其他架构请使用 CI 产物。\n\n"
        "## Changes\n\n"
        + "\n".join(commits) + "\n"
    )

    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(notes)
    print("release notes -> " + out_path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
